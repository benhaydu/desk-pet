"""Turns your own PNGs into firmware/include/team_icons.h for the briefing panels.

Put PNGs in firmware/icons/, named after the card id they're for (leafs.png, saints.png).
Square with a transparent background works best. Both the PNGs and the header this writes
are gitignored, so they stay on your machine. Run from the repo root:

    python tools/make_team_icons.py
"""

from pathlib import Path

from PIL import Image

SIZE = 40  # has to match ICON_SLOT in panel.cpp, which checks it when it compiles
PER_LINE = 12

ROOT = Path(__file__).resolve().parent.parent
ICON_DIR = ROOT / "firmware" / "icons"
OUT = ROOT / "firmware" / "include" / "team_icons.h"


def rgb565(r: int, g: int, b: int) -> int:
    # the screen's 16-bit colour: 5 bits red, 6 green (eyes are most sensitive to it), 5 blue
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def load(path: Path) -> Image.Image:
    image = Image.open(path).convert("RGBA")
    image.thumbnail((SIZE, SIZE), Image.Resampling.LANCZOS)  # shrink to fit, keep the shape

    # centre it on black, so transparent parts become the screen's own background
    canvas = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 255))
    offset = ((SIZE - image.width) // 2, (SIZE - image.height) // 2)
    canvas.alpha_composite(image, offset)
    return canvas.convert("RGB")


def to_array(name: str, image: Image.Image) -> str:
    values = [rgb565(*image.getpixel((x, y))) for y in range(SIZE) for x in range(SIZE)]
    rows = []
    for i in range(0, len(values), PER_LINE):
        rows.append("    " + ", ".join(f"0x{v:04X}" for v in values[i:i + PER_LINE]) + ",")
    return f"static const uint16_t ICON_{name.upper()}[{SIZE * SIZE}] = {{\n" + "\n".join(rows) + "\n};\n"


def main():
    pngs = sorted(ICON_DIR.glob("*.png"))
    if not pngs:
        print(f"no PNGs in {ICON_DIR}, nothing to do")
        return

    arrays = []
    entries = []
    for png in pngs:
        name = png.stem.lower()
        if not name.isidentifier():
            # the name becomes a C variable, so "saints logo.png" can't work
            print(f"skipped {png.name}: rename it to the card id, like leafs.png")
            continue
        arrays.append(to_array(name, load(png)))
        entries.append(f'    {{"{name}", ICON_{name.upper()}}},')
        print(f"{png.name} -> {SIZE}x{SIZE}")

    if not entries:
        return

    header = "\n".join([
        "// generated by tools/make_team_icons.py from your own PNGs.",
        "// don't edit it by hand, and don't commit it: it's in .gitignore",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"static const int TEAM_ICON_SIZE = {SIZE};",
        "",
        *arrays,
        "struct TeamIcon",
        "{",
        "    const char *id;",
        "    const uint16_t *pixels;",
        "};",
        "",
        "static const TeamIcon TEAM_ICONS[] = {",
        *entries,
        "};",
        "",
        "static const int TEAM_ICON_COUNT = sizeof(TEAM_ICONS) / sizeof(TEAM_ICONS[0]);",
        "",
    ])
    OUT.write_text(header)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()